/**
 * Shared icon-container contract. One geometry, surface, border, and colour role
 * for every equivalent icon chip, so pages never restate the container.
 * The frame is decorative: the adjacent label carries the meaning.
 */
export function IconFrame({ name, className }: { name: IconName; className?: string }) {
  return (
    <span className={`icon-frame${className ? ` ${className}` : ''}`} aria-hidden="true">
      <Icon name={name} />
    </span>
  )
}
